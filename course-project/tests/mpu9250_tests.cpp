// Тест із реальною історією. Моя плата з аліекспресу рапортує
// WHO_AM_I = 0x70 (ідентифікатор MPU-6500), хоча магнітометр на ній є -
// це підтвердилось тим, що AK8963 відповів своїм 0x48. Карта регістрів у цих
// чипів однакова, тому клон приймаємо.
// ============================================================================

#include <gtest/gtest.h>

#include "sensors/Mpu9250.h"

TEST(Mpu9250, AcceptsWhoAmIOfRealChipsAndClones) {
    EXPECT_TRUE(mpu9250::isKnownWhoAmI(0x71));   // MPU-9250
    EXPECT_TRUE(mpu9250::isKnownWhoAmI(0x73));   // MPU-9255
    EXPECT_TRUE(mpu9250::isKnownWhoAmI(0x70));   // клон, що рапортує ID MPU-6500
    EXPECT_FALSE(mpu9250::isKnownWhoAmI(0x68));  // MPU-6050, іншої карти регістрів
    EXPECT_FALSE(mpu9250::isKnownWhoAmI(0x00));  // датчик не відповідає
}
